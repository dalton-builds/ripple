#!/usr/bin/env node
/*
 * tools/extract-defaults.mjs
 *
 * The harness carries PRESET_DEFAULTS as a JS object literal: the base every
 * preset is merged over (CONTRACTS.md §4). The era presets on disk are v1 and
 * do not carry the keys Phase 0 added, so a host that does not apply the same
 * defaults renders a different image from the same file.
 *
 * Rather than keep a hand-copied duplicate in C# and hope it stays honest,
 * extract the literal to presets/_defaults.json and have the native host load
 * that. Same convention as extract-shaders.mjs: one authoritative source, a
 * mechanical extraction, and a --check mode that fails when they drift.
 *
 * Usage:
 *   node tools/extract-defaults.mjs [--in harness/index.html] [--out .] [--check]
 */
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const argv = process.argv.slice(2);
const arg = (name, dflt) => {
  const i = argv.indexOf('--' + name);
  return i === -1 ? dflt : argv[i + 1];
};
const IN = resolve(arg('in', 'harness/index.html'));
const OUT = resolve(arg('out', '.'));
const CHECK = argv.includes('--check');
const DEST = join(OUT, 'presets/_defaults.json');

const html = await readFile(IN, 'utf8');

const start = html.indexOf('const PRESET_DEFAULTS = {');
if (start === -1) {
  console.error('PRESET_DEFAULTS literal not found in ' + IN);
  process.exit(1);
}
// Brace-match rather than regex: the literal is nested and contains strings
// with no braces, so a counter is exact and needs no lookahead heroics.
let i = html.indexOf('{', start), depth = 0, end = -1;
for (let k = i; k < html.length; k++) {
  const c = html[k];
  if (c === '{') depth++;
  else if (c === '}') { depth--; if (depth === 0) { end = k + 1; break; } }
}
if (end === -1) {
  console.error('unbalanced braces after PRESET_DEFAULTS');
  process.exit(1);
}

const literal = html.slice(i, end);
let obj;
try {
  obj = Function('"use strict"; return (' + literal + ');')();
} catch (e) {
  console.error('PRESET_DEFAULTS did not evaluate: ' + e.message);
  process.exit(1);
}

const banner = {
  _comment: 'GENERATED by tools/extract-defaults.mjs from harness/index.html — do not edit. '
    + 'This is the base every preset is merged over (CONTRACTS.md §4). Both hosts must apply it.',
};
const text = JSON.stringify(Object.assign(banner, obj), null, 2) + '\n';

if (CHECK) {
  const old = existsSync(DEST) ? await readFile(DEST, 'utf8') : null;
  if (old !== text) {
    console.log('DIFF  presets/_defaults.json');
    console.log('\npresets/_defaults.json is stale — run tools/extract-defaults.mjs');
    process.exit(1);
  }
  console.log('ok    presets/_defaults.json');
  console.log('\ndefaults match the harness');
  process.exit(0);
}

await writeFile(DEST, text, 'utf8');
console.log('wrote presets/_defaults.json (' + Object.keys(obj).length + ' top-level keys)');
