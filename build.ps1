<#
.SYNOPSIS
  Build Ripple with the SDK version global.json pins.

.DESCRIPTION
  The `dotnet` on PATH is not necessarily an SDK install. On this project's
  primary machine it resolves to C:\Program Files\dotnet, which ships the 8.0
  and 9.0 *runtimes* and no SDK at all, so a bare `dotnet build` fails with
  "A compatible .NET SDK was not found" even though the pinned SDK is present
  under the user profile.

  So resolve the muxer explicitly rather than trusting PATH:
    1. $env:DOTNET_ROOT
    2. $HOME\.dotnet\dotnet.exe        <- where a user-scoped install lands
    3. C:\Program Files\dotnet\dotnet.exe
    4. whatever `dotnet` is on PATH
  and take the first one that reports an SDK.

.EXAMPLE
  .\build.ps1
  .\build.ps1 -Configuration Release
  .\build.ps1 -Test
  .\build.ps1 -Publish
#>
[CmdletBinding()]
param(
  [ValidateSet('Debug', 'Release')]
  [string] $Configuration = 'Debug',
  [switch] $Test,
  [switch] $Publish,
  # Position 0 is what keeps -Configuration name-only; see run.ps1.
  [Parameter(ValueFromRemainingArguments = $true, Position = 0)]
  [string[]] $Rest
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

. "$PSScriptRoot\scripts\dotnet-resolve.ps1"
$dotnet = Resolve-RippleDotnet

# .NET 10 writes the newer .slnx by default; accept either, so the wrapper does
# not break if the solution is ever regenerated by an older SDK.
$solution = @("$PSScriptRoot\Ripple.slnx", "$PSScriptRoot\Ripple.sln") |
  Where-Object { Test-Path -LiteralPath $_ } | Select-Object -First 1

if ($Publish) {
  & $dotnet publish "$PSScriptRoot\src\Ripple\Ripple.csproj" -c Release --nologo @Rest
}
elseif ($Test) {
  if (-not $solution) { throw "no Ripple.slnx or Ripple.sln at $PSScriptRoot" }
  & $dotnet test $solution -c $Configuration --nologo @Rest
}
else {
  & $dotnet build "$PSScriptRoot\src\Ripple\Ripple.csproj" -c $Configuration --nologo @Rest
}
exit $LASTEXITCODE
